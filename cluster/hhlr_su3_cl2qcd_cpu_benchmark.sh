#!/bin/bash
#SBATCH --account=mesonqcd
#SBATCH --job-name=su3_cl2_bench
#SBATCH --partition=general2
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=2
#SBATCH --mem=16G
#SBATCH --time=01:00:00
#SBATCH --output=/work/mesonqcd/barros/SU23_freezing/Topological-freezing-in-SU2-3-simulations/logs/su3_cl2_bench_%j.out
#SBATCH --error=/work/mesonqcd/barros/SU23_freezing/Topological-freezing-in-SU2-3-simulations/logs/su3_cl2_bench_%j.err

set -euo pipefail

# Short CPU/OpenCL scaling benchmark for CL2QCD SU(3) heatbath.
# This does not modify CL2QCD and does not write production checkpoints.

module purge

PROJECT_DIR=/work/mesonqcd/barros/SU23_freezing/Topological-freezing-in-SU2-3-simulations
CL2QCD_DIR=/home/mesonqcd/public/barros/cl2qcd_obc_barros
CL2QCD_BIN=${CL2QCD_BIN:-$CL2QCD_DIR/build/su3heatbath}
RESULTS_ROOT=${RESULTS_ROOT:-$PROJECT_DIR/data/results_su3_benchmarks}
LOG_DIR=$PROJECT_DIR/logs

NSPACE=${NSPACE:-40}
NTIME=${NTIME:-80}
BETA=${BETA:-6.80}
PRECISION=${PRECISION:-64}
HOST_SEED=${HOST_SEED:-137}
START_CONDITION=${START_CONDITION:-hot}
USE_OPEN_TEMPORAL_GAUGE_BOUNDARY=${USE_OPEN_TEMPORAL_GAUGE_BOUNDARY:-false}
N_THERMALIZATION_STEPS=${N_THERMALIZATION_STEPS:-0}
N_HEATBATH_STEPS=${N_HEATBATH_STEPS:-3}
N_OVERRELAXATION_STEPS=${N_OVERRELAXATION_STEPS:-15}
ONLINE_MEASURE_EVERY=${ONLINE_MEASURE_EVERY:-1000000}
CREATE_CHECKPOINT_EVERY=${CREATE_CHECKPOINT_EVERY:-0}
OVERWRITE_TEMPORARY_CHECKPOINT_EVERY=${OVERWRITE_TEMPORARY_CHECKPOINT_EVERY:-0}
LOG_LEVEL=${LOG_LEVEL:-INFO}
SPLIT_CPU=${SPLIT_CPU:-false}
SET_POCL_NUM_THREADS=${SET_POCL_NUM_THREADS:-false}
POCL_NUM_THREADS_VALUE=${POCL_NUM_THREADS_VALUE:-${SLURM_CPUS_PER_TASK:-1}}
BENCH_LABEL=${BENCH_LABEL:-baseline}

mkdir -p "$LOG_DIR" "$RESULTS_ROOT"

if [ ! -x "$CL2QCD_BIN" ]; then
    echo "CL2QCD su3heatbath binary is missing or not executable: $CL2QCD_BIN" >&2
    exit 1
fi

BOUNDARY_LABEL=periodic
if [ "$USE_OPEN_TEMPORAL_GAUGE_BOUNDARY" = "true" ] || [ "$USE_OPEN_TEMPORAL_GAUGE_BOUNDARY" = "1" ]; then
    BOUNDARY_LABEL=open
fi

CPUS=${SLURM_CPUS_PER_TASK:-1}
export OMP_NUM_THREADS=$CPUS
export OMP_PROC_BIND=spread
export OMP_PLACES=cores

if [ "$SET_POCL_NUM_THREADS" = "true" ] || [ "$SET_POCL_NUM_THREADS" = "1" ]; then
    export POCL_NUM_THREADS=$POCL_NUM_THREADS_VALUE
else
    unset POCL_NUM_THREADS || true
fi

RUN_LABEL=${RUN_LABEL:-bench_${BENCH_LABEL}_c${CPUS}_T${NTIME}_L${NSPACE}_${BOUNDARY_LABEL}_sweeps${N_HEATBATH_STEPS}_or${N_OVERRELAXATION_STEPS}_${SLURM_JOB_ID:-local}}
RUN_DIR=$RESULTS_ROOT/$RUN_LABEL
INPUT_FILE=$RUN_DIR/input_su3heatbath.txt
SUMMARY_FILE=$RUN_DIR/benchmark_summary.txt

mkdir -p "$RUN_DIR/configs" "$RUN_DIR/prng"

cat > "$INPUT_FILE" <<EOF_INPUT
# Auto-generated by cluster/hhlr_su3_cl2qcd_cpu_benchmark.sh
nSpace=$NSPACE
nTime=$NTIME
useGPU=0
useCPU=1
precision=$PRECISION
hostSeed=$HOST_SEED
startCondition=$START_CONDITION
beta=$BETA
useOpenTemporalGaugeBoundary=$USE_OPEN_TEMPORAL_GAUGE_BOUNDARY
splitCPU=$SPLIT_CPU

nThermalizationSteps=$N_THERMALIZATION_STEPS
nHeatbathSteps=$N_HEATBATH_STEPS
nOverrelaxationSteps=$N_OVERRELAXATION_STEPS
onlineMeasureEvery=$ONLINE_MEASURE_EVERY
createCheckpointEvery=$CREATE_CHECKPOINT_EVERY
overwriteTemporaryCheckpointEvery=$OVERWRITE_TEMPORARY_CHECKPOINT_EVERY
nDigitsInConfCheckpoint=5

confPrefix=configs/conf.
confPostfix=
PRNGPrefix=prng/prng.
PRNGPostfix=
gaugeObsInSingleFile=true
gaugeObsPrefix=gaugeObs
gaugeObsPostfix=.dat
logLevel=$LOG_LEVEL
EOF_INPUT

{
    echo "benchmark_label=$BENCH_LABEL"
    echo "job_id=${SLURM_JOB_ID:-local}"
    echo "node=${SLURMD_NODENAME:-unknown}"
    echo "cpus_per_task=$CPUS"
    echo "omp_num_threads=$OMP_NUM_THREADS"
    echo "omp_proc_bind=$OMP_PROC_BIND"
    echo "omp_places=$OMP_PLACES"
    echo "set_pocl_num_threads=$SET_POCL_NUM_THREADS"
    echo "pocl_num_threads=${POCL_NUM_THREADS:-unset}"
    echo "splitCPU=$SPLIT_CPU"
    echo "nSpace=$NSPACE"
    echo "nTime=$NTIME"
    echo "beta=$BETA"
    echo "boundary=$BOUNDARY_LABEL"
    echo "nThermalizationSteps=$N_THERMALIZATION_STEPS"
    echo "nHeatbathSteps=$N_HEATBATH_STEPS"
    echo "nOverrelaxationSteps=$N_OVERRELAXATION_STEPS"
    echo "createCheckpointEvery=$CREATE_CHECKPOINT_EVERY"
    echo "overwriteTemporaryCheckpointEvery=$OVERWRITE_TEMPORARY_CHECKPOINT_EVERY"
    echo "input_file=$INPUT_FILE"
    echo "run_dir=$RUN_DIR"
} > "$SUMMARY_FILE"

echo "Starting CL2QCD CPU/OpenCL benchmark"
cat "$SUMMARY_FILE"

cd "$RUN_DIR"
SECONDS=0
"$CL2QCD_BIN" "$INPUT_FILE" 2>&1 | tee heatbath.log
elapsed_seconds=$SECONDS

{
    echo "elapsed_seconds=$elapsed_seconds"
    echo "finished=$(date)"
} >> "$SUMMARY_FILE"

echo "Benchmark finished in ${elapsed_seconds}s"
echo "Summary: $SUMMARY_FILE"
