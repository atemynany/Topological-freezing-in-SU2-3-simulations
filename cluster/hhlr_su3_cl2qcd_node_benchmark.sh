#!/bin/bash
#SBATCH --account=mesonqcd
#SBATCH --job-name=su3_cl2_node_bench
#SBATCH --partition=general2
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=40
#SBATCH --mem=0
#SBATCH --time=02:00:00
#SBATCH --output=/work/mesonqcd/barros/SU23_freezing/Topological-freezing-in-SU2-3-simulations/logs/su3_cl2_node_bench_%j.out
#SBATCH --error=/work/mesonqcd/barros/SU23_freezing/Topological-freezing-in-SU2-3-simulations/logs/su3_cl2_node_bench_%j.err

set -euo pipefail

# One-node benchmark for CL2QCD SU(3) CPU/OpenCL usage.
# It tests both single-process scaling knobs and packing several independent
# streams onto one whole-node allocation. CL2QCD source code is not modified.

module purge

PROJECT_DIR=/work/mesonqcd/barros/SU23_freezing/Topological-freezing-in-SU2-3-simulations
CL2QCD_DIR=/home/mesonqcd/public/barros/cl2qcd_obc_barros
CL2QCD_BIN=${CL2QCD_BIN:-$CL2QCD_DIR/build/su3heatbath}
RESULTS_ROOT=${RESULTS_ROOT:-$PROJECT_DIR/data/results_su3_benchmarks}
LOG_DIR=$PROJECT_DIR/logs

NSPACE=${NSPACE:-40}
NTIME=${NTIME:-80}
BETA=${BETA:-6.80}
PRECISION=${PRECISION:-64}
START_CONDITION=${START_CONDITION:-hot}
USE_OPEN_TEMPORAL_GAUGE_BOUNDARY=${USE_OPEN_TEMPORAL_GAUGE_BOUNDARY:-false}
N_THERMALIZATION_STEPS=${N_THERMALIZATION_STEPS:-0}
N_HEATBATH_STEPS=${N_HEATBATH_STEPS:-2}
N_OVERRELAXATION_STEPS=${N_OVERRELAXATION_STEPS:-15}
ONLINE_MEASURE_EVERY=${ONLINE_MEASURE_EVERY:-1000000}
CREATE_CHECKPOINT_EVERY=${CREATE_CHECKPOINT_EVERY:-0}
OVERWRITE_TEMPORARY_CHECKPOINT_EVERY=${OVERWRITE_TEMPORARY_CHECKPOINT_EVERY:-0}
LOG_LEVEL=${LOG_LEVEL:-INFO}
PACK_COUNTS=${PACK_COUNTS-4 8}

mkdir -p "$LOG_DIR" "$RESULTS_ROOT"

if [ ! -x "$CL2QCD_BIN" ]; then
    echo "CL2QCD su3heatbath binary is missing or not executable: $CL2QCD_BIN" >&2
    exit 1
fi

BOUNDARY_LABEL=periodic
if [ "$USE_OPEN_TEMPORAL_GAUGE_BOUNDARY" = "true" ] || [ "$USE_OPEN_TEMPORAL_GAUGE_BOUNDARY" = "1" ]; then
    BOUNDARY_LABEL=open
fi

JOB_ROOT=$RESULTS_ROOT/node_bench_${SLURM_JOB_ID:-local}_T${NTIME}_L${NSPACE}_${BOUNDARY_LABEL}
CSV=$JOB_ROOT/summary.csv
mkdir -p "$JOB_ROOT"

echo "variant,run_index,concurrent,slurm_cpus,omp_threads,pocl_threads,split_cpu,elapsed_seconds,user_seconds,system_seconds,max_rss_kb,exit_code,run_dir" > "$CSV"

write_input() {
    local run_dir=$1
    local seed=$2
    local split_cpu=$3
    local input_file=$run_dir/input_su3heatbath.txt

    mkdir -p "$run_dir/configs" "$run_dir/prng"
    cat > "$input_file" <<EOF_INPUT
# Auto-generated by cluster/hhlr_su3_cl2qcd_node_benchmark.sh
nSpace=$NSPACE
nTime=$NTIME
useGPU=0
useCPU=1
precision=$PRECISION
hostSeed=$seed
startCondition=$START_CONDITION
beta=$BETA
useOpenTemporalGaugeBoundary=$USE_OPEN_TEMPORAL_GAUGE_BOUNDARY
splitCPU=$split_cpu

nThermalizationSteps=$N_THERMALIZATION_STEPS
nHeatbathSteps=$N_HEATBATH_STEPS
nOverrelaxationSteps=$N_OVERRELAXATION_STEPS
onlineMeasureEvery=$ONLINE_MEASURE_EVERY
createCheckpointEvery=$CREATE_CHECKPOINT_EVERY
overwriteTemporaryCheckpointEvery=$OVERWRITE_TEMPORARY_CHECKPOINT_EVERY
nDigitsInConfCheckpoint=5

confPrefix=configs/conf.
confPostfix=
PRNGPrefix=prng/prng.
PRNGPostfix=
gaugeObsInSingleFile=true
gaugeObsPrefix=gaugeObs
gaugeObsPostfix=.dat
logLevel=$LOG_LEVEL
EOF_INPUT
}

run_one() {
    local variant=$1
    local run_index=$2
    local concurrent=$3
    local omp_threads=$4
    local pocl_threads=$5
    local split_cpu=$6
    local seed=$7
    local run_dir=$JOB_ROOT/${variant}_${run_index}
    local input_file=$run_dir/input_su3heatbath.txt
    local time_file=$run_dir/time.csv
    local status=0

    write_input "$run_dir" "$seed" "$split_cpu"

    (
        cd "$run_dir"
        export OMP_NUM_THREADS=$omp_threads
        export OMP_PROC_BIND=spread
        export OMP_PLACES=cores
        if [ "$pocl_threads" = "unset" ]; then
            unset POCL_NUM_THREADS || true
        else
            export POCL_NUM_THREADS=$pocl_threads
        fi

        set +e
        TIMEFORMAT="${variant},${run_index},${concurrent},${SLURM_CPUS_PER_TASK:-40},${omp_threads},${pocl_threads},${split_cpu},%R,%U,%S,0"
        { time "$CL2QCD_BIN" "$input_file" > heatbath.log 2>&1; } 2> "$time_file"
        status=$?
        set -e
        if [ -s "$time_file" ]; then
            while IFS= read -r line; do
                echo "${line},${status},${run_dir}" >> "$CSV"
            done < "$time_file"
        else
            echo "${variant},${run_index},${concurrent},${SLURM_CPUS_PER_TASK:-40},${omp_threads},${pocl_threads},${split_cpu},0,0,0,0,${status},${run_dir}" >> "$CSV"
        fi
        exit "$status"
    )
}

run_pack() {
    local count=$1
    local variant=pack${count}_unset
    local pids=()
    local status=0

    echo "===== ${variant}: ${count} concurrent independent CL2QCD processes ====="
    for i in $(seq 0 $((count - 1))); do
        run_one "$variant" "$i" "$count" 1 unset false $((137 + i * 97)) &
        pids+=("$!")
    done

    for pid in "${pids[@]}"; do
        if ! wait "$pid"; then
            status=1
        fi
    done

    return "$status"
}

echo "Starting CL2QCD SU(3) one-node benchmark"
echo "job_root=$JOB_ROOT"
echo "node=${SLURMD_NODENAME:-unknown}"
echo "lattice=${NSPACE}^3 x ${NTIME}"
echo "boundary=$BOUNDARY_LABEL"
echo "sweeps=$N_HEATBATH_STEPS"
echo "overrelaxation=$N_OVERRELAXATION_STEPS"
echo "csv=$CSV"

run_one single_unset 0 1 40 unset false 137
run_one single_pocl40 0 1 40 40 false 234
run_one single_split 0 1 40 unset true 331
run_one single_pocl40_split 0 1 40 40 true 428

for count in $PACK_COUNTS; do
    run_pack "$count"
done

echo "Benchmark complete"
echo "Summary CSV: $CSV"
cat "$CSV"
